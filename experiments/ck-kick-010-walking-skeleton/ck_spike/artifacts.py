"""Disposable artifact and publication helpers for CK-KICK-010.

This module deliberately knows nothing about fields, meshes, or the shape of a
walking-skeleton bundle.  It supplies the replaceable mechanics needed by a
future command adapter:

* canonical JSON and SHA-256 helpers;
* a manifest which hashes every supplied artifact except itself;
* an explicit build/environment identity record; and
* fail-safe, staged publication of a caller-written and caller-validated
  bundle.

The output format here is spike-local.  In particular, the identity record is
build provenance, not a semantic source-node identity, and hashes are
artifact-local rather than durable semantic identifiers.
"""

from __future__ import annotations

import ctypes
import errno
import hashlib
import importlib.metadata
import json
import math
import os
import platform
import shutil
import sys
import tempfile
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any, TypeAlias

from .diagnostics import Diagnostic, Phase, Severity


MANIFEST_NAME = "manifest.json"
MANIFEST_FORMAT = "ck-kick-010-bundle-manifest-v1"
IDENTITY_FORMAT = "ck-kick-010-build-identity-v1"
REQUIRED_DEPENDENCIES: tuple[str, ...] = ("numpy", "scikit-image", "trimesh")


class ArtifactError(Exception):
    """Base exception carrying structured artifact/publication diagnostics."""

    def __init__(self, diagnostics: tuple[Diagnostic, ...]):
        self.diagnostics = diagnostics
        super().__init__(
            "; ".join(f"{item.code} at {item.path}" for item in diagnostics)
        )


class ArtifactPublicationError(ArtifactError):
    """Raised when writing, validation, or publication cannot complete."""


# Short aliases make the exception boundary convenient for command adapters
# without introducing a second diagnostic type in this disposable host.
PublicationError = ArtifactPublicationError
BundleArtifactError = ArtifactError


@dataclass(frozen=True)
class PublicationResult:
    """Result of a successful publication.

    The staging directory is intentionally not returned: it has been renamed
    into ``target`` and its temporary name must not become build metadata.
    """

    target: Path
    artifact_names: tuple[str, ...]


def _reject_non_deterministic_values(value: Any, path: str = "$") -> None:
    """Reject values which JSON would silently coerce ambiguously.

    ``json.dumps(..., allow_nan=False)`` handles non-finite floats.  The
    explicit walk additionally rejects path objects, bytes, sets, and mapping
    keys which could otherwise be converted differently by callers.  String
    values are intentionally not treated as paths: diagnostic JSON pointers
    conventionally begin with ``/`` and are valid deterministic strings.
    """

    if isinstance(value, float) and not math.isfinite(value):
        raise ValueError(f"non-finite number at {path}")
    if isinstance(value, (Path, os.PathLike, bytes, bytearray, memoryview)):
        raise TypeError(f"non-JSON deterministic value at {path}: {type(value).__name__}")
    if isinstance(value, (set, frozenset)):
        raise TypeError(f"unordered value at {path}: {type(value).__name__}")
    if isinstance(value, Mapping):
        for key, item in value.items():
            if not isinstance(key, str):
                raise TypeError(f"JSON object key at {path} must be a string")
            _reject_non_deterministic_values(item, f"{path}.{key}")
        return
    if isinstance(value, (list, tuple)):
        for index, item in enumerate(value):
            _reject_non_deterministic_values(item, f"{path}[{index}]")


def canonical_json_bytes(value: Any) -> bytes:
    """Serialize a JSON-compatible value to deterministic UTF-8 bytes.

    The policy is sorted object keys, compact separators, UTF-8 characters
    (rather than escaped ASCII), and exactly one trailing LF.  NaN and either
    infinity are rejected.  No timestamp, path, random ID, or temporary name
    is generated by this helper; callers must provide only stable payload
    values.
    """

    _reject_non_deterministic_values(value)
    try:
        text = json.dumps(
            value,
            ensure_ascii=False,
            allow_nan=False,
            sort_keys=True,
            separators=(",", ":"),
        )
    except (TypeError, ValueError):
        # Preserve the standard exception types while keeping the public
        # failure useful to callers and tests.
        raise
    return (text + "\n").encode("utf-8")


def canonical_json_text(value: Any) -> str:
    """Return :func:`canonical_json_bytes` decoded as UTF-8 text."""

    return canonical_json_bytes(value).decode("utf-8")


# A descriptive alias for adapters that prefer a verb in the API name.
canonicalize_json = canonical_json_bytes


def sha256_bytes(data: bytes | bytearray | memoryview) -> str:
    """Return the lowercase SHA-256 hex digest of ``data``."""

    return hashlib.sha256(bytes(data)).hexdigest()


def sha256_file(path: str | os.PathLike[str]) -> str:
    """Return the lowercase SHA-256 hex digest of a file."""

    digest = hashlib.sha256()
    with open(path, "rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


hash_bytes = sha256_bytes
hash_file = sha256_file


ArtifactValue: TypeAlias = bytes | bytearray | memoryview | str | os.PathLike[str]


def _artifact_name(name: str, manifest_name: str = MANIFEST_NAME) -> str:
    """Validate and return a relative, POSIX-like artifact name."""

    if not isinstance(name, str) or not name:
        raise ValueError("artifact names must be non-empty strings")
    if "\\" in name or name.startswith("/") or os.path.isabs(name):
        raise ValueError(f"artifact name must be relative: {name!r}")
    parts = name.split("/")
    if any(part in {"", ".", ".."} for part in parts):
        raise ValueError(f"artifact name must be normalized and relative: {name!r}")
    if name == manifest_name:
        raise ValueError("the manifest cannot hash itself")
    return name


def _artifact_bytes(value: ArtifactValue) -> bytes:
    if isinstance(value, (bytes, bytearray, memoryview)):
        return bytes(value)
    if isinstance(value, os.PathLike):
        return Path(value).read_bytes()
    if isinstance(value, str):
        # String mapping values are content, not paths.  This avoids silently
        # putting an absolute path into a deterministic bundle payload.
        return value.encode("utf-8")
    raise TypeError(f"unsupported artifact value: {type(value).__name__}")


def build_manifest(
    artifacts: Mapping[str, ArtifactValue],
    *,
    manifest_name: str = MANIFEST_NAME,
) -> dict[str, Any]:
    """Build a deterministic manifest for supplied non-manifest artifacts.

    Artifact names are normalized relative names and are sorted by
    :func:`canonical_json_bytes` when serialized.  Values may be bytes/content
    strings or paths to files; only their bytes are represented in the
    manifest.  The manifest has no self-reference.
    """

    _artifact_name(manifest_name, manifest_name="__manifest_name_never_matches__")
    if not artifacts:
        # Empty bundles are not useful, but leaving this policy to the caller's
        # validator keeps this mechanical helper geometry- and shape-agnostic.
        names: dict[str, str] = {}
    else:
        names = {}
        for raw_name, value in artifacts.items():
            name = _artifact_name(raw_name, manifest_name=manifest_name)
            if name in names:
                raise ValueError(f"duplicate artifact name: {name!r}")
            names[name] = sha256_bytes(_artifact_bytes(value))
    return {
        "format": MANIFEST_FORMAT,
        "artifacts": {name: names[name] for name in sorted(names)},
    }


def manifest_bytes(
    artifacts: Mapping[str, ArtifactValue],
    *,
    manifest_name: str = MANIFEST_NAME,
) -> bytes:
    """Serialize :func:`build_manifest` with the canonical JSON policy."""

    return canonical_json_bytes(build_manifest(artifacts, manifest_name=manifest_name))


create_manifest = build_manifest


def add_manifest(
    artifacts: Mapping[str, ArtifactValue],
    *,
    manifest_name: str = MANIFEST_NAME,
) -> dict[str, bytes]:
    """Return copied artifact bytes plus a self-excluding manifest."""

    copied: dict[str, bytes] = {}
    for raw_name, value in artifacts.items():
        name = _artifact_name(raw_name, manifest_name=manifest_name)
        copied[name] = _artifact_bytes(value)
    copied[manifest_name] = manifest_bytes(copied, manifest_name=manifest_name)
    return {name: copied[name] for name in sorted(copied)}


def installed_dependency_versions(
    required: tuple[str, ...] = REQUIRED_DEPENDENCIES,
) -> dict[str, str | None]:
    """Capture sorted installed distribution versions.

    Recording every installed distribution is a mechanically conservative way
    to include the relevant transitive environment without parsing dependency
    markers or leaking installation paths.  The three spike dependencies are
    always present as keys, with ``null`` if unavailable in the interpreter.
    """

    candidates: dict[str, set[str]] = {}
    for distribution in importlib.metadata.distributions():
        name = distribution.metadata.get("Name") or distribution.name
        if not name:
            continue
        normalized = name.replace("_", "-").replace(".", "-").lower()
        candidates.setdefault(normalized, set()).add(distribution.version)
    # A healthy environment has one distribution per normalized name.  If a
    # broken environment exposes duplicates, sorting still makes the record
    # deterministic rather than depending on metadata enumeration order.
    versions = {name: sorted(values)[0] for name, values in candidates.items()}
    result: dict[str, str | None] = {name: versions.get(name) for name in required}
    for name in sorted(versions):
        result.setdefault(name, versions[name])
    return result


def _payload_hash(value: Any) -> str:
    if isinstance(value, (bytes, bytearray, memoryview)):
        return sha256_bytes(value)
    return sha256_bytes(canonical_json_bytes(value))


def build_identity(
    *,
    spike_revision: int | str,
    seed: int | str,
    input_payload: Any = None,
    config_payload: Any = None,
    compiler_identity: Any = None,
    source_identity: Any = None,
    compiler_revision: Any = None,
    source_revision: Any = None,
    input_hash: str | None = None,
    config_hash: str | None = None,
    dependency_versions: Mapping[str, str | None] | None = None,
) -> dict[str, Any]:
    """Return explicit deterministic build and environment provenance.

    ``compiler_identity`` and ``source_identity`` are caller-owned values;
    this seam never invokes Git and never discovers source paths.  Raw bytes
    are hashed directly, while JSON-compatible input/config values are first
    canonicalized.  Source-node labels and artifact hashes intentionally do
    not appear in this record.
    """

    if compiler_identity is None and compiler_revision is not None:
        compiler_identity = compiler_revision
    if source_identity is None and source_revision is not None:
        source_identity = source_revision
    if input_hash is None:
        input_hash = _payload_hash(input_payload)
    if config_hash is None:
        config_hash = _payload_hash(config_payload)
    dependencies = dict(
        dependency_versions
        if dependency_versions is not None
        else installed_dependency_versions()
    )
    identity = {
        "format": IDENTITY_FORMAT,
        "spike_revision": spike_revision,
        "seed": seed,
        "canonical_input_sha256": input_hash,
        "canonical_config_sha256": config_hash,
        "compiler_identity": compiler_identity,
        "source_identity": source_identity,
        "python": {
            "implementation": platform.python_implementation(),
            "version": list(sys.version_info[:3]),
        },
        "platform": {
            "system": platform.system(),
            "release": platform.release(),
            "machine": platform.machine(),
            "architecture": platform.architecture()[0],
        },
        "dependencies": {
            name: dependencies[name] for name in sorted(dependencies)
        },
    }
    # Validate caller-provided identity values now, so the returned record is
    # guaranteed to be accepted by canonical_json_bytes later.
    _reject_non_deterministic_values(identity)
    return identity


environment_identity = build_identity
make_build_identity = build_identity


def _diagnostic(
    code: str,
    phase: Phase,
    path: str,
    message: str,
) -> Diagnostic:
    return Diagnostic(
        code=code,
        severity=Severity.ERROR,
        phase=phase,
        path=path,
        related_source_labels=(),
        message=message,
    )


def _raise_artifact(
    code: str,
    phase: Phase,
    message: str,
    *,
    path: str = "/bundle",
) -> None:
    raise ArtifactPublicationError((_diagnostic(code, phase, path, message),))


def _resolved(path: str | os.PathLike[str]) -> Path:
    # strict=False allows us to validate a new target while still resolving
    # ``..`` and symlinked ancestors for protected-target comparisons.
    return Path(path).expanduser().resolve(strict=False)


def _default_repository_root() -> Path:
    # This is an explicit disposable-host derivation, not a Git lookup.  The
    # module lives at <repository>/experiments/<host>/ck_spike/artifacts.py.
    return Path(__file__).resolve().parents[3]


def _default_host_root() -> Path:
    return Path(__file__).resolve().parents[1]


def _is_protected_target(
    target: Path,
    *,
    repository_root: str | os.PathLike[str] | None,
    disposable_host_root: str | os.PathLike[str] | None,
) -> bool:
    protected = {
        Path(os.path.abspath(os.sep)).resolve(),
        Path.home().resolve(strict=False),
        _resolved(repository_root) if repository_root is not None else _default_repository_root(),
        _resolved(disposable_host_root)
        if disposable_host_root is not None
        else _default_host_root(),
    }
    return target in protected


def _validate_output_target(
    final_path: str | os.PathLike[str],
    *,
    repository_root: str | os.PathLike[str] | None,
    disposable_host_root: str | os.PathLike[str] | None,
) -> tuple[Path, Path]:
    # Normalize ``..`` and make the path absolute without resolving the final
    # component.  Resolving the final component first would turn a symlink
    # target into its referent and could accidentally permit publication over
    # a broken symlink.
    target = Path(os.path.abspath(os.fspath(Path(final_path).expanduser())))
    protected_target = target.parent.resolve(strict=False) / target.name
    if _is_protected_target(
        protected_target,
        repository_root=repository_root,
        disposable_host_root=disposable_host_root,
    ):
        _raise_artifact(
            "PROTECTED_OUTPUT_TARGET",
            Phase.PUBLICATION,
            "output target is a protected broad directory",
        )
    if os.path.lexists(target):
        _raise_artifact(
            "OUTPUT_TARGET_EXISTS",
            Phase.PUBLICATION,
            "output target already exists; overwrite is not supported",
        )
    parent = target.parent
    try:
        parent_stat = os.lstat(parent)
    except OSError as exc:
        _raise_artifact(
            "INVALID_OUTPUT_PARENT",
            Phase.PUBLICATION,
            f"output parent must be an existing directory ({exc.__class__.__name__})",
        )
    if not os.path.isdir(parent) or os.path.islink(parent):
        _raise_artifact(
            "INVALID_OUTPUT_PARENT",
            Phase.PUBLICATION,
            "output parent must be an existing non-symlink directory",
        )
    # Keep the local variable's use explicit for static analysers and to make
    # clear that lstat, rather than a followed stat, guards this boundary.
    del parent_stat
    return target, parent


def _cleanup_staging(staging: Path) -> None:
    """Remove only this invocation's exact staging path, never its parent."""

    try:
        info = os.lstat(staging)
    except FileNotFoundError:
        return
    if os.path.islink(staging) or not os.path.isdir(staging):
        os.unlink(staging)
    else:
        # shutil.rmtree does not follow symlinks inside the directory.
        shutil.rmtree(staging)


def _atomic_rename_noreplace(source: Path, target: Path) -> None:
    """Atomically rename a directory without replacing an existing target.

    Linux provides exactly the required operation through ``renameat2`` with
    ``RENAME_NOREPLACE``.  On platforms without an equivalent primitive this
    helper refuses publication rather than using a check-then-rename sequence
    that could overwrite a target appearing in the race window.
    """

    if sys.platform.startswith("linux"):
        libc = ctypes.CDLL(None, use_errno=True)
        renameat2 = getattr(libc, "renameat2", None)
        if renameat2 is not None:
            renameat2.argtypes = [ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_uint]
            renameat2.restype = ctypes.c_int
            result = renameat2(
                -100,  # AT_FDCWD
                os.fsencode(str(source)),
                -100,
                os.fsencode(str(target)),
                1,  # RENAME_NOREPLACE
            )
            if result == 0:
                return
            error = ctypes.get_errno()
            if error == errno.EEXIST:
                raise FileExistsError(errno.EEXIST, "publication target appeared")
            if error not in {errno.ENOSYS, errno.EINVAL, errno.ENOTSUP}:
                raise OSError(error, os.strerror(error))
    if os.name == "nt":
        # Windows' MoveFileEx-backed os.rename does not replace an existing
        # destination when the replace flag is omitted.  Keep the explicit
        # precheck for a useful race diagnostic.
        if os.path.lexists(target):
            raise FileExistsError(errno.EEXIST, "publication target appeared")
        os.rename(source, target)
        return
    raise OSError(errno.ENOTSUP, "atomic no-replace directory rename unavailable")


def write_bundle_files(
    directory: str | os.PathLike[str],
    artifacts: Mapping[str, ArtifactValue],
    *,
    manifest_name: str = MANIFEST_NAME,
) -> tuple[str, ...]:
    """Write explicit mapping values below ``directory``.

    This helper does not invent completeness rules.  The caller can pass
    ``add_manifest(artifacts)`` and apply any bundle-shape validator required
    for a valid or diagnostics-only run.
    """

    root = Path(directory)
    written: list[str] = []
    for raw_name, value in artifacts.items():
        name = _artifact_name(raw_name, manifest_name="__allow_manifest__")
        destination = root.joinpath(*name.split("/"))
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(_artifact_bytes(value))
        written.append(name)
    return tuple(sorted(written))


BundleWriter: TypeAlias = Callable[[Path], Any]
BundleValidator: TypeAlias = Callable[[Path], Any]


def publish_bundle(
    final_path: str | os.PathLike[str],
    bundle: Mapping[str, ArtifactValue] | BundleWriter | None = None,
    validator: BundleValidator | None = None,
    *,
    files: Mapping[str, ArtifactValue] | None = None,
    writer: BundleWriter | None = None,
    repository_root: str | os.PathLike[str] | None = None,
    disposable_host_root: str | os.PathLike[str] | None = None,
) -> PublicationResult:
    """Stage, validate, and publish a caller-defined bundle.

    ``bundle`` may be a mapping or a callback receiving the staging directory;
    the keyword aliases ``files`` and ``writer`` are accepted for readability.
    A mapping is written with :func:`write_bundle_files`.  A callback may write
    directly and optionally return a mapping, which is then written as well.
    The validator must return ``False`` to reject (``None`` is accepted for a
    callback that signals success by completing normally); an exception is a
    structured artifact failure.  Existing targets are never overwritten.
    """

    if bundle is not None and (files is not None or writer is not None):
        _raise_artifact(
            "AMBIGUOUS_BUNDLE_WRITER",
            Phase.ARTIFACT,
            "provide one bundle, files, or writer argument",
        )
    source: Mapping[str, ArtifactValue] | BundleWriter | None
    source = files if files is not None else writer if writer is not None else bundle
    if source is None:
        _raise_artifact(
            "MISSING_BUNDLE_WRITER",
            Phase.ARTIFACT,
            "a bundle mapping or writer callback is required",
        )
    if validator is None:
        _raise_artifact(
            "MISSING_BUNDLE_VALIDATOR",
            Phase.ARTIFACT,
            "a validator callback is required",
        )

    target, parent = _validate_output_target(
        final_path,
        repository_root=repository_root,
        disposable_host_root=disposable_host_root,
    )
    staging: Path | None = None
    try:
        # mkdtemp creates exactly one directory in the already validated
        # parent, so staging and final publication are on one filesystem.
        staging = Path(
            tempfile.mkdtemp(prefix=f".{target.name}.staging-", dir=str(parent))
        )
        written: tuple[str, ...] = ()
        if isinstance(source, Mapping):
            written = write_bundle_files(staging, source)
        else:
            try:
                callback_result = source(staging)
            except Exception as exc:
                _raise_artifact(
                    "BUNDLE_WRITER_FAILED",
                    Phase.ARTIFACT,
                    f"bundle writer failed ({exc.__class__.__name__})",
                )
            if isinstance(callback_result, Mapping):
                written = write_bundle_files(staging, callback_result)

        try:
            validation_result = validator(staging)
        except Exception as exc:
            _raise_artifact(
                "BUNDLE_VALIDATOR_FAILED",
                Phase.ARTIFACT,
                f"bundle validator failed ({exc.__class__.__name__})",
            )
        if validation_result is False or getattr(validation_result, "ok", True) is False:
            _raise_artifact(
                "BUNDLE_VALIDATION_FAILED",
                Phase.ARTIFACT,
                "bundle validator rejected the staged bundle",
            )

        # Check once before the kernel-level no-replace operation to provide a
        # clear diagnostic on platforms without renameat2 as well.
        if os.path.lexists(target):
            _raise_artifact(
                "OUTPUT_TARGET_APPEARED",
                Phase.PUBLICATION,
                "output target appeared before atomic publication",
            )
        try:
            _atomic_rename_noreplace(staging, target)
        except FileExistsError:
            _raise_artifact(
                "OUTPUT_TARGET_APPEARED",
                Phase.PUBLICATION,
                "output target appeared during atomic publication",
            )
        staging = None
        if not written:
            try:
                written = tuple(
                    sorted(
                        str(path.relative_to(target)).replace(os.sep, "/")
                        for path in target.rglob("*")
                        if path.is_file()
                    )
                )
            except OSError:
                written = ()
        return PublicationResult(target=target, artifact_names=written)
    except ArtifactPublicationError:
        raise
    except Exception as exc:
        if isinstance(exc, OSError) and exc.errno in {
            errno.ENOTSUP,
            errno.ENOSYS,
            errno.EINVAL,
        }:
            _raise_artifact(
                "ATOMIC_PUBLICATION_UNAVAILABLE",
                Phase.PUBLICATION,
                "this host lacks an atomic no-replace directory rename",
            )
        _raise_artifact(
            "BUNDLE_PUBLICATION_FAILED",
            Phase.PUBLICATION,
            f"unexpected publication failure ({exc.__class__.__name__})",
        )
    finally:
        if staging is not None:
            try:
                _cleanup_staging(staging)
            except Exception:
                # Never broaden cleanup to a parent or sibling.  The original
                # typed failure remains the useful diagnostic boundary.
                pass


